#!/usr/bin/env python3
"""Generates docs/catalog.md and the asset tables inside each plugins/<pack>/README.md
from the agents' and skills' frontmatter, so the docs never drift from the files.

    python3 scripts/gen-catalog.py           # write
    python3 scripts/gen-catalog.py --check   # exit 1 if anything is out of date (CI)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKS = ["core", "openspec", "design", "stack", "ai-engineering"]
BEGIN, END = "<!-- catalog:begin -->", "<!-- catalog:end -->"


def frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit(f"{path}: no frontmatter")
    out = {}
    for line in m.group(1).splitlines():
        km = re.match(r"^([a-z_-]+):\s*(.*)$", line)
        if km:
            k, v = km.groups()
            v = v.strip()
            if v.startswith('"') and v.endswith('"'):
                v = json.loads(v)
            elif v.startswith("'") and v.endswith("'"):
                v = v[1:-1].replace("''", "'")
            out[k] = v
    return out


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def pack_assets(pack: str):
    base = ROOT / "plugins" / pack
    agents = []
    for f in sorted((base / "agents").glob("*.md")) if (base / "agents").is_dir() else []:
        fm = frontmatter(f)
        if fm.get("name") != f.stem:
            raise SystemExit(f"{f}: name '{fm.get('name')}' != file name")
        agents.append((fm["name"], fm.get("model", ""), fm.get("tools", ""), fm["description"], f.relative_to(base)))
    skills = []
    for d in sorted((base / "skills").iterdir()) if (base / "skills").is_dir() else []:
        f = d / "SKILL.md"
        if not f.is_file():
            continue
        fm = frontmatter(f)
        if fm.get("name") != d.name:
            raise SystemExit(f"{f}: name '{fm.get('name')}' != folder name")
        skills.append((fm["name"], fm["description"], f.relative_to(base)))
    return agents, skills


def tables(pack: str, link_prefix: str) -> str:
    agents, skills = pack_assets(pack)
    out = []
    if agents:
        out += ["**Agents**", "", "| Agent | Model | Tools | What it does / when to use |", "|---|---|---|---|"]
        out += [f"| [`{n}`]({link_prefix}{p}) | {m} | {cell(t)} | {cell(d)} |" for n, m, t, d, p in agents]
        out.append("")
    if skills:
        out += ["**Skills** (invoke with `/<name>` or let Claude pick them by description)", "",
                "| Skill | What it does / when to use |", "|---|---|"]
        out += [f"| [`{n}`]({link_prefix}{p}) | {cell(d)} |" for n, d, p in skills]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def splice(text: str, body: str, where: Path) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{where}: missing {BEGIN} / {END} markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{body}{END}{tail}"


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    sections = []
    for pack in PACKS:
        manifest = json.loads((ROOT / "plugins" / pack / ".claude-plugin" / "plugin.json").read_text())
        sections.append(f"## {manifest['name']}\n\n{manifest['description']} — [README](../plugins/{pack}/README.md)\n\n"
                        + tables(pack, f"../plugins/{pack}/"))
        readme = ROOT / "plugins" / pack / "README.md"
        new = splice(readme.read_text(encoding="utf-8"), tables(pack, ""), readme)
        if readme.read_text(encoding="utf-8") != new:
            stale.append(readme)
            if not check:
                readme.write_text(new, encoding="utf-8")
    catalog = ROOT / "docs" / "catalog.md"
    body = ("# Catalog\n\n<!-- Generated by scripts/gen-catalog.py from each file's frontmatter. Do not edit by hand. -->\n\n"
            "Every agent and skill in devkit, by pack.\n\n" + "\n".join(sections))
    if not catalog.exists() or catalog.read_text(encoding="utf-8") != body:
        stale.append(catalog)
        if not check:
            catalog.write_text(body, encoding="utf-8")
    if check and stale:
        print("out of date (run python3 scripts/gen-catalog.py):", *[str(p.relative_to(ROOT)) for p in stale], sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
